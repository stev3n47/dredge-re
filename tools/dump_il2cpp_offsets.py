#!/usr/bin/env python3
"""Extract il2cpp_* runtime entry-point VMAs from a Pokémon GO UnityFramework.

UnityFramework ships with an empty export trie (POGO-FINDINGS: "24-byte
export trie, exports nothing"), but every il2cpp_* runtime glue symbol
is still present in the classic LC_SYMTAB. This tool parses LC_SYMTAB
directly — llvm-nm hangs on a 191 MB binary — and emits a C header with
the VMAs for the SpooferProPlus bridge to use at runtime.

Usage:
  python tools/dump_il2cpp_offsets.py <UnityFramework-binary> <out.h>

At runtime the SpooferProPlus bridge:
  1. dlopens UnityFramework (which is always loaded once Pokémon GO starts).
  2. Looks up its image header by name.
  3. For each il2cpp_* VMA emitted here, computes
     `fn_ptr = image_header + slide + vma - preferred_base`
     (preferred_base is 0 for PoGo's UnityFramework; the slide is dyld's
      ASLR offset returned by `_dyld_get_image_vmaddr_slide`).
  4. Verifies `fn_ptr` points inside __TEXT before calling.

This keeps us version-resilient-ish: we ship one header per PoGo version
and the dylib picks the right one at build time.

Note about `n_value` semantics: for an arm64 Mach-O dylib, LC_SYMTAB
`n_value` is the virtual address (VMA) of the symbol in the dylib's
preferred load-time layout. UnityFramework has preferred_base = 0 and
sections with `vma == file_offset` (we verified separately on the
SpooferPro build), so these values are also file offsets. The bridge
uses them as VMAs so an ASLR-shifted image still resolves correctly.
"""
import argparse
import struct
import sys
import mmap

# Full set of il2cpp_* glue we may want. The bridge compiles with all of
# them declared; features that aren't used link but don't call.
WANTED = [
    'il2cpp_init',
    'il2cpp_domain_get',
    'il2cpp_domain_get_assemblies',
    'il2cpp_assembly_get_image',
    'il2cpp_image_get_name',
    'il2cpp_image_get_class',
    'il2cpp_image_get_class_count',
    'il2cpp_class_get_name',
    'il2cpp_class_get_namespace',
    'il2cpp_class_get_method_from_name',
    'il2cpp_class_get_field_from_name',
    'il2cpp_field_static_get_value',
    'il2cpp_runtime_invoke',
    'il2cpp_runtime_class_init',
    'il2cpp_thread_attach',
    'il2cpp_thread_detach',
    'il2cpp_thread_current',
    'il2cpp_object_new',
    'il2cpp_object_get_class',
    'il2cpp_string_new',
    'il2cpp_string_chars',
    'il2cpp_string_length',
    'il2cpp_array_new',
    'il2cpp_type_get_name',
    'il2cpp_type_get_object',
    'il2cpp_class_from_type',
    'il2cpp_class_get_type',
    'il2cpp_gchandle_new',
    'il2cpp_method_get_param',
    # Phase 4 additions — introspection + field lookup
    'il2cpp_method_get_name',
    'il2cpp_method_get_param_name',
    'il2cpp_method_get_param_count',
    'il2cpp_method_get_return_type',
    'il2cpp_class_get_methods',
    'il2cpp_class_get_fields',
    'il2cpp_field_get_name',
    'il2cpp_field_get_type',
    'il2cpp_field_get_flags',
    'il2cpp_class_get_type_token',
    'il2cpp_class_num_fields',
]

MH_MAGIC_64 = 0xFEEDFACF
LC_SYMTAB = 0x02


def dump(unity_path: str, header_path: str, version_tag: str):
    with open(unity_path, 'rb') as f:
        mm = mmap.mmap(f.fileno(), 0, prot=mmap.PROT_READ)

    magic, cputype, cpusub, ft, ncmds, soc = struct.unpack('<6I', mm[:24])
    if magic != MH_MAGIC_64:
        sys.exit(f'error: {unity_path!r} is not an arm64 Mach-O (magic 0x{magic:x})')

    off = 32
    symtab = None
    for _ in range(ncmds):
        cmd, sz = struct.unpack('<II', mm[off:off + 8])
        if cmd == LC_SYMTAB:
            symoff, nsyms, stroff, strsize = struct.unpack('<IIII', mm[off + 8:off + 24])
            symtab = (symoff, nsyms, stroff, strsize)
            break
        off += sz
    if not symtab:
        sys.exit('error: no LC_SYMTAB in input')

    symoff, nsyms, stroff, strsize = symtab
    strtab = mm[stroff:stroff + strsize]

    want = set(WANTED)
    found = {}
    for i in range(nsyms):
        entry = mm[symoff + i * 16:symoff + i * 16 + 16]
        n_strx, n_type, n_sect, n_desc, n_value = struct.unpack('<IBBHQ', entry)
        if n_strx == 0 or n_strx >= strsize:
            continue
        end = strtab.find(b'\x00', n_strx)
        if end < 0:
            continue
        name = strtab[n_strx:end].decode('ascii', 'replace')
        clean = name.lstrip('_')
        if clean in want:
            found[clean] = n_value

    missing = [n for n in WANTED if n not in found]
    if missing:
        print(f'warn: {len(missing)}/{len(WANTED)} entry points missing:')
        for m in missing:
            print(f'  {m}')

    # Emit header
    lines = [
        '// Auto-generated by tools/dump_il2cpp_offsets.py — do not edit.',
        f'// Source: {unity_path}',
        f'// Tag:    {version_tag}',
        f'// Found:  {len(found)}/{len(WANTED)} il2cpp_* entry points',
        '//',
        '// Each value is the virtual-address OFFSET of the named symbol inside',
        '// UnityFramework (preferred base = 0; vma == file offset for this build).',
        '// At runtime, add the dyld slide to each to get a callable function pointer.',
        '',
        '#ifndef SPP_IL2CPP_OFFSETS_H',
        '#define SPP_IL2CPP_OFFSETS_H',
        '',
        f'#define SPP_IL2CPP_VERSION_TAG "{version_tag}"',
        '',
    ]
    for name in WANTED:
        v = found.get(name, 0)
        macro = 'SPP_' + name.upper() + '_OFF'
        if v:
            lines.append(f'#define {macro} 0x{v:x}uLL')
        else:
            lines.append(f'// #define {macro} <missing>')
    lines.append('')
    lines.append('#endif  // SPP_IL2CPP_OFFSETS_H')

    with open(header_path, 'w') as out:
        out.write('\n'.join(lines) + '\n')
    print(f'wrote {header_path}  ({len(found)}/{len(WANTED)} symbols)')


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('unity', help='path to UnityFramework binary')
    p.add_argument('out', help='output C header path')
    p.add_argument('--tag', default='unknown', help='version tag, e.g. "pogo-0.743"')
    args = p.parse_args()
    dump(args.unity, args.out, args.tag)


if __name__ == '__main__':
    main()
